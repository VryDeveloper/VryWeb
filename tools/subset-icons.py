"""Builds css/icons.css and assets/fonts/*.woff2 with only the icons the site uses.

The full icon fonts cost ~700 KB (devicon alone is a 578 KB TTF) for ~85 glyphs.
Run again after adding an icon class anywhere in index.html or js/:

    python tools/subset-icons.py        (needs: pip install fonttools brotli)
"""
import io, re, sys, urllib.request
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SETS = {
    'bi': ('bootstrap-icons', 'https://cdn.jsdelivr.net/npm/bootstrap-icons@1.11.3/font/bootstrap-icons.min.css',
           'https://cdn.jsdelivr.net/npm/bootstrap-icons@1.11.3/font/fonts/bootstrap-icons.woff2'),
    'devicon': ('devicon', 'https://cdn.jsdelivr.net/gh/devicons/devicon@v2.16.0/devicon.min.css',
                'https://cdn.jsdelivr.net/gh/devicons/devicon@v2.16.0/fonts/devicon.ttf'),
}
BASE = {
    'bi': '.bi::before,[class*=" bi-"]::before,[class^=bi-]::before{display:inline-block;font-family:bootstrap-icons!important;font-style:normal;font-weight:400!important;font-variant:normal;text-transform:none;line-height:1;vertical-align:-.125em;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}',
    'devicon': '[class^=devicon-],[class*=" devicon-"]{font-family:devicon!important;speak:never;font-style:normal;font-weight:400;font-variant:normal;text-transform:none;line-height:1;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}',
}
EXTRA = {'colored', 'bi'}  # modifier classes allowed next to an icon class


def get(url):
    with urllib.request.urlopen(url) as r:
        return r.read()


def used_classes():
    text = (ROOT / 'index.html').read_text(encoding='utf-8')
    text += ''.join(p.read_text(encoding='utf-8') for p in (ROOT / 'js').rglob('*.js'))
    return set(re.findall(r'\b((?:bi|devicon)-[a-z0-9-]+)', text))


def build(prefix, used):
    family, css_url, font_url = SETS[prefix]
    css = get(css_url).decode('utf-8-sig')
    rules, points = [], set()
    for selectors, body in re.findall(r'([^{}@]+)\{([^{}]*)\}', css):
        keep = []
        for sel in selectors.split(','):
            classes = set(re.findall(r'\.([a-z0-9-]+)', sel))
            mine = {c for c in classes if c.startswith(prefix + '-')}
            if mine and mine <= used and classes - mine <= EXTRA:
                keep.append(sel.strip())
        if not keep:
            continue
        rules.append(f'{",".join(keep)}{{{body}}}')
        m = re.search(r'content:\s*"(\\[0-9a-fA-F]+|.)"', body)
        if m:
            c = m.group(1)
            points.add(int(c[1:], 16) if c.startswith('\\') else ord(c))
    missing = sorted(c for c in used if c.startswith(prefix + '-') and not any(re.search(rf'\.{re.escape(c)}(?![a-z0-9-])', r) for r in rules))
    if missing:
        sys.exit(f'not in {family}: {missing}')

    font = TTFont(io.BytesIO(get(font_url)))
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = []
    opts.name_IDs = ['*']
    s = subset.Subsetter(opts)
    s.populate(unicodes=points)
    s.subset(font)
    out = ROOT / 'assets' / 'fonts' / f'{family}.woff2'
    out.parent.mkdir(parents=True, exist_ok=True)
    font.flavor = 'woff2'
    font.save(out)
    face = f'@font-face{{font-family:{family};font-display:block;src:url("../assets/fonts/{family}.woff2") format("woff2")}}'
    print(f'{family}: {len(points)} glyphs, {out.stat().st_size // 1024} KB')
    return '\n'.join([face, BASE[prefix], *rules])


if __name__ == '__main__':
    used = used_classes()
    parts = [build(p, used) for p in SETS]
    header = '/* generated by tools/subset-icons.py: only the icons the site uses. Licenses: Bootstrap Icons (MIT), Devicon (MIT). */\n'
    (ROOT / 'css' / 'icons.css').write_text(header + '\n'.join(parts) + '\n', encoding='utf-8')
